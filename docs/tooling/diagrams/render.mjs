import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { renderMermaidSVG } from 'beautiful-mermaid';

const directory = new URL('../../public/images/architecture/', import.meta.url);
const snippets = new URL('../../public/snippets/diagrams/', import.meta.url);
const diagrams = JSON.parse(await readFile(new URL('diagrams.json', import.meta.url), 'utf8'));
const check = process.argv.includes('--check');
const site = JSON.parse(await readFile(new URL('../../public/docs.json', import.meta.url), 'utf8'));
const colors = {
  paper: [site.background.color.light, site.background.color.dark], ink: ['#20231F', '#F0F1EB'],
  accent: [site.colors.primary, site.colors.light], muted: ['#52594E', '#B3B9AC'],
  line: ['#9CA59A', '#697265'], surface: ['#F2F3EE', '#22251F'],
  border: ['#B9C1B4', '#515B4B'], proof: ['#EAF0FF', '#232F50'],
  result: ['#E5F5EE', '#19382E'], resultLine: ['#278160', '#8CD2B6'],
  stop: ['#FAE8E5', '#422823'], stopLine: ['#BC6258', '#F0A99C'],
};
function palette(theme) {
  return Object.fromEntries(Object.entries(colors).map(([name, values]) =>
    [name, theme === 'inline' ? `var(--diagram-${name})` : values[theme === 'light' ? 0 : 1]]));
}
function render(source, theme, name) {
  const c = palette(theme);
  const styled = `${source}\nclassDef proof fill:${c.proof},stroke:${c.accent},color:${c.ink}\nclassDef result fill:${c.result},stroke:${c.resultLine},color:${c.ink}\nclassDef stop fill:${c.stop},stroke:${c.stopLine},color:${c.ink}`;
  let svg = renderMermaidSVG(styled, {
    bg: c.paper, fg: c.ink, accent: c.accent, muted: c.muted,
    line: c.line, surface: c.surface, border: c.border,
    font: site.fonts.family, padding: 24, nodeSpacing: 28, layerSpacing: 36,
    transparent: theme === 'inline',
  });
  // The page already loads SUSE. Standalone files use the local sans-serif fallback.
  svg = svg.replace(/^\s*@import url\([^\n]+\);\s*$/gm, '');
  if (/<(?:script|foreignObject|animate|image)\b|@import|(?:href|src)=["']https?:|url\(\s*["']?https?:/i.test(svg)) {
    throw new Error('The renderer produced active or remote SVG content');
  }
  if (theme === 'inline') {
    // Inline SVG styles must not affect other page icons or diagrams.
    svg = svg.replace('  text {', '  .kast-diagram text {').replace('  svg {', '  .kast-diagram svg {');
  }
  // Multiple figures share a page. Keep marker references local to their diagram.
  svg = svg.replace(/(?<![-\w])id="([^"]+)"/g, (_, id) => `id="${name}-${id}"`)
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${name}-${id})`);
  return svg;
}
function component({ name, label, component }, svg) {
  const source = `/images/architecture/${name}.mmd`;
  const light = `/images/architecture/${name}.light.svg`;
  const dark = `/images/architecture/${name}.dark.svg`;
  return `// Generated by docs/tooling/diagrams/render.mjs. Edit the .mmd source.\nexport const ${component} = () => {\n  const [expanded, setExpanded] = useState(false);\n  return (\n    <figure className="kast-diagram not-prose">\n      <div className={expanded ? "kd-canvas kd-expanded" : "kd-canvas"} role="img" aria-label=${JSON.stringify(label)} tabIndex={0} dangerouslySetInnerHTML={{ __html: ${JSON.stringify(svg)} }} />\n      <figcaption>\n        <span>${label}</span>\n        <div className="kd-actions">\n          <button type="button" aria-pressed={expanded} onClick={() => setExpanded(!expanded)}>{expanded ? "Fit diagram" : "Enlarge diagram"}</button>\n          <a href=${JSON.stringify(source)}>Mermaid source</a>\n          <a className="kd-light-link" href=${JSON.stringify(light)}>Open SVG</a>\n          <a className="kd-dark-link" href=${JSON.stringify(dark)}>Open SVG</a>\n        </div>\n      </figcaption>\n    </figure>\n  );\n};\n`;
}
const sources = (await readdir(directory)).filter(name => name.endsWith('.mmd')).sort();
const expected = diagrams.map(item => `${item.name}.mmd`).sort();
if (JSON.stringify(sources) !== JSON.stringify(expected)) throw new Error('Diagram inventory does not match diagrams.json');
if (!check) await mkdir(snippets, { recursive: true });
const themeCss = ['light', 'dark'].map((theme, index) => {
  const selector = theme === 'light' ? '.kast-diagram' : '.dark .kast-diagram';
  const properties = Object.entries(colors).map(([name, values]) => `  --diagram-${name}: ${values[index]};`).join('\n');
  return `${selector} {\n${properties}\n}`;
}).join('\n');
const outputs = [[new URL('../../public/diagram-theme.css', import.meta.url),
  `/* Generated by docs/tooling/diagrams/render.mjs. */\n${themeCss}\n`]];
for (const diagram of diagrams) {
  const source = await readFile(new URL(`${diagram.name}.mmd`, directory), 'utf8');
  for (const theme of ['light', 'dark']) {
    outputs.push([new URL(`${diagram.name}.${theme}.svg`, directory), render(source, theme, diagram.name) + '\n']);
  }
  outputs.push([new URL(`${diagram.name}.jsx`, snippets), component(diagram, render(source, 'inline', diagram.name))]);
}
for (const [path, content] of outputs) {
  if (check) {
    const current = await readFile(path, 'utf8').catch(() => null);
    if (current !== content) throw new Error(`Stale diagram: ${fileURLToPath(path)}`);
  } else await writeFile(path, content);
}
console.log(`${check ? 'Checked' : 'Rendered'} ${diagrams.length} diagrams and ${outputs.length} projections.`);
