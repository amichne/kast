private fun epochCase(
    caseId: Kvp015CaseId,
    movedSignals: List<Kvp015SignalCategory>,
    projectTransitions: List<Kvp015ProjectModelTransition> = emptyList(),
    relation: Kvp015SampleRelation = Kvp015SampleRelation.CHANGED,
    dumbModeSamples: List<Kvp015DumbModeState> = listOf(
        Kvp015DumbModeState.SMART,
        Kvp015DumbModeState.SMART,
    ),
    dumbTransitions: List<Kvp015DumbModeTransition> = emptyList(),
    vfsEventCount: Int = 0,
) = Kvp015CaseDocument(
    caseId,
    SAMPLES_PER_CASE,
    movedSignals,
    projectTransitions,
    dumbModeSamples,
    dumbTransitions,
    vfsEventCount,
    relation,
    relation,
)

private fun Kvp015EpochLedgerDocument.forbiddenEffectCounts(): List<Int> = listOf(
    vfsRefreshCount,
    gradleImportCount,
    repositoryWalkCount,
    sourceHashCount,
    semanticJobCount,
    edtWorkCount,
    blockingWaitCount,
)

private fun rejected(
    failure: Kvp015EpochLedgerReportFailure,
): Kvp015EpochLedgerReportAdmission = Kvp015EpochLedgerReportAdmission.Rejected(failure)

private const val SCHEMA_VERSION = 1
private const val IDE_BUILD = "262.9437.185"
private const val SAMPLES_PER_CASE = 2
private const val STORM_EVENT_COUNT = 1_000
private val CONSTANT_ZERO_VFS_AUTHORITIES = listOf(
    "VirtualFileManager.modificationCount",
    "VirtualFileManager.structureModificationCount",
)

private val EPOCH_LEDGER_JSON = Json {
    encodeDefaults = true
    explicitNulls = true
    ignoreUnknownKeys = false
    isLenient = false
    prettyPrint = true
    prettyPrintIndent = "    "
}
