internal enum class Kvp015EpochLedgerReportFailure {
    MALFORMED_DOCUMENT,
    NON_CANONICAL_DOCUMENT,
    SCHEMA_VERSION_MISMATCH,
    AUTHORITY_MISMATCH,
    IDE_BUILD_MISMATCH,
    SIGNAL_SET_MISMATCH,
    CONSTANT_ZERO_AUTHORITY_NOT_REJECTED,
    CASE_SET_MISMATCH,
    SAMPLE_COUNT_MISMATCH,
    STORM_EVENT_COUNT_MISMATCH,
    CASE_EXPECTATION_MISMATCH,
    FORBIDDEN_EFFECT_OBSERVED,
}

internal class AdmittedKvp015EpochLedgerReport private constructor(
    val canonicalDocument: String,
    val authority: String,
    val ideBuild: String,
    val signalCount: Int,
    val caseCount: Int,
    val sampleCount: Int,
    val stormEventCount: Int,
) {
    companion object {
        /**
         * Proof transition: `String -> Kvp015EpochLedgerReportAdmission`.
         *
         * Establishes canonical generated bytes for the exact IDEA-262 READ_EPOCH signal and case
         * ledger. The admitted report proves ordered signal authority, two samples per case, every
         * required movement, rejection of constant-zero VFS manager counters, the 1,000-event
         * storm, and zero forbidden stronger effects. [Kvp015EpochLedgerReportFailure] closes every
         * expected report failure; raw JSON may leave only at this Gradle receipt boundary.
         */
        fun admit(raw: String): Kvp015EpochLedgerReportAdmission {
            val document = try {
                EPOCH_LEDGER_JSON.decodeFromString(Kvp015EpochLedgerDocument.serializer(), raw)
            } catch (_: SerializationException) {
                return rejected(Kvp015EpochLedgerReportFailure.MALFORMED_DOCUMENT)
            } catch (_: IllegalArgumentException) {
                return rejected(Kvp015EpochLedgerReportFailure.MALFORMED_DOCUMENT)
            }
            val expectedCases = canonicalCases()
            val failure = when {
                document.schemaVersion != SCHEMA_VERSION ->
                    Kvp015EpochLedgerReportFailure.SCHEMA_VERSION_MISMATCH
                document.authority != Kvp015ReportAuthority.READ_EPOCH ->
                    Kvp015EpochLedgerReportFailure.AUTHORITY_MISMATCH
                document.ideBuild != IDE_BUILD ->
                    Kvp015EpochLedgerReportFailure.IDE_BUILD_MISMATCH
                document.signals != canonicalSignals() ->
                    Kvp015EpochLedgerReportFailure.SIGNAL_SET_MISMATCH
                document.rejectedConstantZeroAuthorities != CONSTANT_ZERO_VFS_AUTHORITIES ->
                    Kvp015EpochLedgerReportFailure.CONSTANT_ZERO_AUTHORITY_NOT_REJECTED
                document.cases.map(Kvp015CaseDocument::caseId) !=
                    expectedCases.map(Kvp015CaseDocument::caseId) ->
                    Kvp015EpochLedgerReportFailure.CASE_SET_MISMATCH
                document.cases.any { case -> case.sampleCount != SAMPLES_PER_CASE } ->
                    Kvp015EpochLedgerReportFailure.SAMPLE_COUNT_MISMATCH
                document.cases.singleOrNull {
                    case -> case.caseId == Kvp015CaseId.VFS_EVENT_STORM
                }?.vfsEventCount != STORM_EVENT_COUNT ->
                    Kvp015EpochLedgerReportFailure.STORM_EVENT_COUNT_MISMATCH
                document.cases != expectedCases ->
                    Kvp015EpochLedgerReportFailure.CASE_EXPECTATION_MISMATCH
                document.forbiddenEffectCounts().any { count -> count != 0 } ->
                    Kvp015EpochLedgerReportFailure.FORBIDDEN_EFFECT_OBSERVED
                else -> null
            }
            if (failure != null) return rejected(failure)
            val canonical = EPOCH_LEDGER_JSON.encodeToString(
                Kvp015EpochLedgerDocument.serializer(),
                document,
            ) + "\n"
            if (raw != canonical) {
                return rejected(Kvp015EpochLedgerReportFailure.NON_CANONICAL_DOCUMENT)
            }
            return Kvp015EpochLedgerReportAdmission.Admitted(
                AdmittedKvp015EpochLedgerReport(
                    canonical,
                    document.authority.name,
                    document.ideBuild,
                    document.signals.size,
                    document.cases.size,
                    document.cases.sumOf(Kvp015CaseDocument::sampleCount),
                    document.cases.single {
                        case -> case.caseId == Kvp015CaseId.VFS_EVENT_STORM
                    }.vfsEventCount,
                ),
            )
        }
    }
}

internal sealed interface Kvp015EpochLedgerReportAdmission {
    data class Admitted(
        val report: AdmittedKvp015EpochLedgerReport,
    ) : Kvp015EpochLedgerReportAdmission

    data class Rejected(
        val failure: Kvp015EpochLedgerReportFailure,
    ) : Kvp015EpochLedgerReportAdmission
}

@CacheableTask
abstract class GenerateKvp015EpochLedgerReportTask : DefaultTask() {
    @get:OutputFile
    abstract val reportFile: RegularFileProperty

    /** Writes the canonical generated KVP-015 READ_EPOCH characterization ledger. */
    @TaskAction
    fun generate() {
        writeTextAtomically(reportFile.get().asFile.toPath(), canonicalKvp015EpochLedgerReport())
    }
}

private fun canonicalKvp015EpochLedgerReport(): String = EPOCH_LEDGER_JSON.encodeToString(
    Kvp015EpochLedgerDocument.serializer(),
    Kvp015EpochLedgerDocument(
        schemaVersion = SCHEMA_VERSION,
        authority = Kvp015ReportAuthority.READ_EPOCH,
        ideBuild = IDE_BUILD,
        signals = canonicalSignals(),
        rejectedConstantZeroAuthorities = CONSTANT_ZERO_VFS_AUTHORITIES,
        cases = canonicalCases(),
        vfsRefreshCount = 0,
        gradleImportCount = 0,
        repositoryWalkCount = 0,
        sourceHashCount = 0,
        semanticJobCount = 0,
        edtWorkCount = 0,
        blockingWaitCount = 0,
    ),
) + "\n"

