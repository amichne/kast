ROOT = Path(__file__).resolve().parents[3]
MANIFEST = "docs/okf-public.json"
OUTPUT = "docs/public/snippets/okf"
GENERATED = "{/* Generated by docs/tooling/okf_public.py."
PARSER = Path(__file__).with_name("markdown") / "project-okf.ts"
MAX_BYTES = 8 * 1024 * 1024


class Code(StrEnum):
    INPUT = "OKF_INPUT"
    PATH = "OKF_PATH"
    TRACKING = "OKF_TRACKING"
    ATTRIBUTION = "OKF_ATTRIBUTION"
    MARKDOWN = "OKF_MARKDOWN"
    DRIFT = "OKF_PROJECTION_DRIFT"
    IO = "OKF_IO"


@dataclass(frozen=True, slots=True)
class Failure:
    code: Code
    path: str


class EvidenceStatus(StrEnum):
    MATCHED = "MATCHED"
    CHANGED = "CHANGED"
    NOT_ASSESSED = "NOT_ASSESSED"


@dataclass(frozen=True, slots=True)
class Evidence:
    claim: str
    resource: str
    recordedVersion: str
    currentVersion: str
    status: EvidenceStatus


@dataclass(frozen=True, slots=True)
class View:
    route: str
    frontmatter: str
    concepts: tuple[str, ...]
    imports: tuple[str, ...]
    diagrams: tuple[str, ...]
    anchors: tuple[str, ...]
    introduction: str | None = None


@dataclass(frozen=True, slots=True)
class Authored:
    route: str
    purpose: str


@dataclass(frozen=True, slots=True)
class Asset:
    source: str
    destination: str


@dataclass(frozen=True, slots=True)
class Manifest:
    views: tuple[View, ...]
    authored: tuple[Authored, ...]
    assets: tuple[Asset, ...] = ()


@dataclass(frozen=True, slots=True)
class OutputPaths:
    paths: tuple[str, ...]


def output_paths(manifest: Manifest) -> OutputPaths:
    return OutputPaths(
        (
            OUTPUT,
            *(f"docs/public/{view.route}.mdx" for view in manifest.views),
            *(asset.destination for asset in manifest.assets),
        )
    )


