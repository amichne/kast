package io.github.amichne.kast.relation.intellij

import io.github.amichne.kast.kernel.ElapsedTimeLimitMillis
import io.github.amichne.kast.kernel.Refinement
import io.github.amichne.kast.kernel.ResourceBudget
import io.github.amichne.kast.kernel.ResultLimit
import io.github.amichne.kast.kernel.WorkUnitLimit
import io.github.amichne.kast.relation.contract.CallbackInvocationFlowCause
import java.io.ByteArrayInputStream
import java.io.IOException
import java.io.InputStream
import java.util.concurrent.CancellationException
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/** These stream checks do not establish compiler validity for a classfile. */
class ContractClassDigestContentsTest {
    @Test
    fun `runner hashes beyond one MiB while bounded mode keeps its binary allowance`() {
        val bytes = ByteArray(1_048_577) { ((it * 31) % 251).toByte() }
        val runner =
            ByteArrayInputStream(bytes).use {
                contractClassDigestContents(it, ResourceBudget.RunnerControlled) {}
            }
        // Independent Python hashlib oracle for all 1,048,577 generated bytes.
        assertEquals("82bc07217c48a73c887818b05e1ad391ded5c197b8f3dab97edfcba5d8f8bcab", runner.refined().value)
        val bounded = ByteArrayInputStream(bytes).use { contractClassDigestContents(it, boundedResources()) {} }
        assertEquals(Refinement.Rejected(CallbackInvocationFlowCause.DEPENDENCY_BINARY_UNAVAILABLE), bounded)
    }

    @Test
    fun `bounded mode hashes the complete one MiB allowance`() {
        val bytes = ByteArray(1_048_576) { ((it * 31) % 251).toByte() }
        val digest = ByteArrayInputStream(bytes).use { contractClassDigestContents(it, boundedResources()) {} }
        assertEquals("3617860390ce98fe34c1bb89382ea7122d3b6890069e30a078892492ba0c774d", digest.refined().value)
    }

    @Test
    fun `neither mode admits an empty binary stream`() {
        for (resources in listOf(boundedResources(), ResourceBudget.RunnerControlled)) {
            val result = ByteArrayInputStream(byteArrayOf()).use { contractClassDigestContents(it, resources) {} }
            assertEquals(Refinement.Rejected(CallbackInvocationFlowCause.DEPENDENCY_BINARY_UNAVAILABLE), result)
        }
    }

    @Test
    fun `runner cancellation stops the stream without a digest`() {
        val bytes = ByteArray(1_048_577)
        val input = ByteArrayInputStream(bytes)
        var cancellationPoints = 0
        assertThrows(CancellationException::class.java) {
            input.use {
                contractClassDigestContents(it, ResourceBudget.RunnerControlled) {
                    cancellationPoints++
                    if (cancellationPoints == 3) throw CancellationException("The caller stops the digest")
                }
            }
        }
        assertEquals(3, cancellationPoints)
        assertTrue(input.available() > 0)
    }

    @Test
    fun `stream failure stays a finite unavailable binary outcome`() {
        val input =
            object : InputStream() {
                override fun read(): Int = throw IOException("The input failed")
            }
        val result = input.use { contractClassDigestContents(it, ResourceBudget.RunnerControlled) {} }
        assertEquals(Refinement.Rejected(CallbackInvocationFlowCause.DEPENDENCY_BINARY_UNAVAILABLE), result)
    }
}

private fun boundedResources(): ResourceBudget.Bounded =
    ResourceBudget(
        ResultLimit.parse(1).refined(),
        WorkUnitLimit.parse(1).refined(),
        ElapsedTimeLimitMillis.parse(1).refined(),
    )

private fun <V, F> Refinement<V, F>.refined(): V =
    when (this) {
        is Refinement.Refined -> value
        is Refinement.Rejected -> error("Invalid fixture: $failure")
    }
