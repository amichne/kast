def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def nav_paths(value: object) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, list):
        return [path for item in value for path in nav_paths(item)]
    if isinstance(value, dict):
        return [path for item in value.values() for path in nav_paths(item)]
    raise AssertionError(f"unsupported navigation value: {value!r}")


def check_config() -> None:
    require((ROOT / "docs/build_public_site.py").is_file(), "public site builder is missing")
    config = tomllib.loads((ROOT / "zensical.toml").read_text())["project"]
    require(config["docs_dir"] == "docs/public", "Zensical docs_dir changed")
    require(config["site_dir"] == "site", "Zensical site_dir changed")
    require(
        config["extra_javascript"] == ["javascripts/accessibility.js"],
        "unexpected global JavaScript surface",
    )
    require(config["plugins"]["search"]["enabled"] is False, "minimal site search is enabled")
    nav = config["nav"]
    top_labels = [next(iter(item)) for item in nav]
    require(top_labels == EXPECTED_TOP_NAV, f"unexpected top navigation: {top_labels}")
    destinations = nav_paths(nav)
    require(destinations == list(PAGES), f"navigation and page contract differ: {destinations}")


