"""Project attributed, tracked OKF concepts into the public Mintlify site."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
from dataclasses import asdict, dataclass
from enum import StrEnum
from pathlib import Path, PurePosixPath
from typing import TypeGuard

import yaml

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = "docs/okf-public.json"
OUTPUT = "docs/public/snippets/okf"
GENERATED = "{/* Generated by docs/tooling/okf_public.py."
PARSER = Path(__file__).with_name("markdown") / "project-okf.ts"
MAX_BYTES = 8 * 1024 * 1024


class Code(StrEnum):
    INPUT = "OKF_INPUT"
    PATH = "OKF_PATH"
    TRACKING = "OKF_TRACKING"
    ATTRIBUTION = "OKF_ATTRIBUTION"
    MARKDOWN = "OKF_MARKDOWN"
    DRIFT = "OKF_PROJECTION_DRIFT"
    IO = "OKF_IO"


@dataclass(frozen=True, slots=True)
class Failure:
    code: Code
    path: str


class EvidenceStatus(StrEnum):
    MATCHED = "MATCHED"
    CHANGED = "CHANGED"
    NOT_ASSESSED = "NOT_ASSESSED"


@dataclass(frozen=True, slots=True)
class Evidence:
    claim: str
    resource: str
    recordedVersion: str
    currentVersion: str
    status: EvidenceStatus


@dataclass(frozen=True, slots=True)
class View:
    route: str
    frontmatter: str
    concepts: tuple[str, ...]
    imports: tuple[str, ...]
    diagrams: tuple[str, ...]
    anchors: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class Authored:
    route: str
    purpose: str


@dataclass(frozen=True, slots=True)
class Manifest:
    views: tuple[View, ...]
    authored: tuple[Authored, ...]


@dataclass(frozen=True, slots=True)
class _Concept:
    path: str
    sha256: str
    claimsSha256: str
    body: str
    evidence: tuple[Evidence, ...]


@dataclass(frozen=True, slots=True)
class _Document:
    path: str
    body: str


@dataclass(frozen=True, slots=True)
class _RenderRequest:
    documents: tuple[_Document, ...]
    routes: dict[str, str]


@dataclass(frozen=True, slots=True)
class Artifact:
    path: str
    text: str


@dataclass(frozen=True, slots=True)
class ConceptReport:
    path: str
    sha256: str
    claimsSha256: str
    evidence: tuple[Evidence, ...]


@dataclass(frozen=True, slots=True)
class Report:
    concepts: tuple[ConceptReport, ...]
    views: tuple[str, ...]
    authored: tuple[Authored, ...]
    type: str = "ATTRIBUTED_OKF_PROJECTION"


@dataclass(frozen=True, slots=True)
class Projection:
    artifacts: tuple[Artifact, ...]
    report: Report


def _record(value: object) -> TypeGuard[dict[str, object]]:
    return _mapping(value) and all(isinstance(key, str) for key in value)


def _mapping(value: object) -> TypeGuard[dict[object, object]]:
    return isinstance(value, dict)


def _objects(value: object) -> TypeGuard[list[object]]:
    return isinstance(value, list)


def _strings(value: object) -> TypeGuard[list[str]]:
    return _objects(value) and all(isinstance(item, str) for item in value)


def _unique(pairs: list[tuple[str, object]]) -> dict[str, object]:
    values: dict[str, object] = {}
    for key, value in pairs:
        if key in values:
            raise ValueError("duplicate JSON key")
        values[key] = value
    return values


def _json(text: str, path: str) -> object:
    try:
        value: object = json.loads(text, object_pairs_hook=_unique)
    except ValueError:
        return Failure(Code.INPUT, path)
    return value


def _path(value: str, prefix: str, suffix: str) -> bool:
    path = PurePosixPath(value)
    return (
        value.startswith(prefix)
        and value.endswith(suffix)
        and not path.is_absolute()
        and ".." not in path.parts
        and path.as_posix() == value
        and re.fullmatch(r"[a-zA-Z0-9_./-]+", value) is not None
    )


def _read(root: Path, name: str) -> str | Failure:
    path = root / name
    if path.resolve() != root.resolve() / name or path.is_symlink():
        return Failure(Code.PATH, name)
    try:
        if path.stat().st_size > MAX_BYTES:
            return Failure(Code.INPUT, name)
        return path.read_bytes().decode("utf-8")
    except (OSError, UnicodeError):
        return Failure(Code.IO, name)


def parse_manifest(text: str) -> Manifest | Failure:
    raw = _json(text, MANIFEST)
    if not _record(raw) or set(raw) != {"schemaVersion", "views", "authored"}:
        return Failure(Code.INPUT, MANIFEST)
    if type(raw["schemaVersion"]) is not int or raw["schemaVersion"] != 1:
        return Failure(Code.INPUT, MANIFEST)
    if not _objects(raw["views"]) or not raw["views"] or not _objects(raw["authored"]):
        return Failure(Code.INPUT, MANIFEST)
    views: list[View] = []
    authored: list[Authored] = []
    for view in raw["views"]:
        if not _record(view) or set(view) != {
            "route",
            "frontmatter",
            "concepts",
            "imports",
            "diagrams",
            "anchors",
        }:
            return Failure(Code.INPUT, MANIFEST)
        route, frontmatter = view["route"], view["frontmatter"]
        concepts, imports, diagrams, anchors = (
            view["concepts"],
            view["imports"],
            view["diagrams"],
            view["anchors"],
        )
        if (
            not isinstance(route, str)
            or not _path(route, "", "")
            or not isinstance(frontmatter, str)
            or not frontmatter.strip()
            or not _strings(concepts)
            or not concepts
            or len(set(concepts)) != len(concepts)
            or not all(_path(item, "openwiki/", ".md") for item in concepts)
            or not _strings(imports)
            or not _strings(diagrams)
            or not _strings(anchors)
        ):
            return Failure(Code.INPUT, MANIFEST)
        if any(
            re.fullmatch(
                r'import \{ [A-Za-z]+Diagram \} from "/snippets/diagrams/[a-z-]+\.jsx"', item
            )
            is None
            for item in imports
        ):
            return Failure(Code.INPUT, MANIFEST)
        if any(re.fullmatch(r"<[A-Za-z]+Diagram />", item) is None for item in diagrams):
            return Failure(Code.INPUT, MANIFEST)
        if any(re.fullmatch(r"[a-z0-9_-]+", item) is None for item in anchors):
            return Failure(Code.INPUT, MANIFEST)
        views.append(
            View(
                route, frontmatter, tuple(concepts), tuple(imports), tuple(diagrams), tuple(anchors)
            )
        )
    for item in raw["authored"]:
        if not _record(item) or set(item) != {"route", "purpose"}:
            return Failure(Code.INPUT, MANIFEST)
        route, purpose = item["route"], item["purpose"]
        if (
            not isinstance(route, str)
            or not _path(route, "", "")
            or not isinstance(purpose, str)
            or purpose
            not in {
                "generated-glossary",
                "schema-binding",
                "canonical-coverage-gap",
                "recorded-illustration",
                "reader-navigation",
                "reader-task-or-contract",
            }
        ):
            return Failure(Code.INPUT, MANIFEST)
        authored.append(Authored(route, purpose))
    routes = [view.route for view in views] + [item.route for item in authored]
    if len(set(routes)) != len(routes):
        return Failure(Code.INPUT, MANIFEST)
    return Manifest(tuple(views), tuple(authored))


def _frontmatter(text: str, path: str) -> str | Failure:
    sections = text.split("---\n", 2)
    if len(sections) != 3 or sections[0]:
        return Failure(Code.ATTRIBUTION, path)
    try:
        loader = yaml.SafeLoader(sections[1])
        try:
            node = loader.get_single_node()
        finally:
            loader.dispose()
        if not isinstance(node, yaml.MappingNode):
            return Failure(Code.ATTRIBUTION, path)
        keys = [key.value for key, _value in node.value if isinstance(key, yaml.ScalarNode)]
        if len(keys) != len(node.value) or len(set(keys)) != len(keys):
            return Failure(Code.ATTRIBUTION, path)
        value: object = yaml.safe_load(sections[1])
    except yaml.YAMLError:
        return Failure(Code.ATTRIBUTION, path)
    if not _record(value):
        return Failure(Code.ATTRIBUTION, path)
    concept_type = value.get("type")
    if not isinstance(concept_type, str) or not concept_type.strip():
        return Failure(Code.ATTRIBUTION, path)
    return sections[2].strip() + "\n"


def _concept(root: Path, name: str, tracked: frozenset[str]) -> _Concept | Failure:
    claims_path = "openwiki/.claims/" + name.removeprefix("openwiki/").removesuffix(".md") + ".json"
    for path in (name, claims_path):
        if path not in tracked:
            return Failure(Code.TRACKING, path)
    text = _read(root, name)
    if isinstance(text, Failure):
        return text
    body = _frontmatter(text, name)
    if isinstance(body, Failure):
        return body
    digest = hashlib.sha256(text.encode()).hexdigest()
    claims_text = _read(root, claims_path)
    if isinstance(claims_text, Failure):
        return claims_text
    raw = _json(claims_text, claims_path)
    if (
        not _record(raw)
        or type(raw.get("schemaVersion")) is not int
        or raw.get("schemaVersion") != 1
        or raw.get("pageVersion") != "sha256:" + digest
        or not _objects(raw.get("claims"))
    ):
        return Failure(Code.ATTRIBUTION, name)
    claims = raw["claims"]
    if not _objects(claims) or not claims:
        return Failure(Code.ATTRIBUTION, name)
    evidence: list[Evidence] = []
    for claim in claims:
        if not _record(claim) or not isinstance(claim.get("id"), str):
            return Failure(Code.ATTRIBUTION, name)
        identifier, refs = claim["id"], claim.get("evidence")
        if not isinstance(identifier, str) or not _objects(refs) or not refs:
            return Failure(Code.ATTRIBUTION, name)
        for ref in refs:
            if (
                not _record(ref)
                or not isinstance(ref.get("resource"), str)
                or not isinstance(ref.get("version"), str)
            ):
                return Failure(Code.ATTRIBUTION, name)
            resource, version = ref["resource"], ref["version"]
            if (
                not isinstance(resource, str)
                or not isinstance(version, str)
                or not version
                or not resource.startswith("repo://")
            ):
                return Failure(Code.ATTRIBUTION, name)
            source, separator, _span = resource.removeprefix("repo://").partition("#")
            if not _path(source, "", ""):
                return Failure(Code.PATH, source)
            if source not in tracked:
                return Failure(Code.TRACKING, source)
            content = _read(root, source)
            if isinstance(content, Failure):
                return content
            current = "repo-file-v1:sha256:" + hashlib.sha256(content.encode()).hexdigest()
            status = EvidenceStatus.NOT_ASSESSED
            if not separator and re.fullmatch(r"repo-file-v1:sha256:[a-f0-9]{64}", version):
                status = EvidenceStatus.MATCHED if version == current else EvidenceStatus.CHANGED
            evidence.append(Evidence(identifier, resource, version, current, status))
    return _Concept(
        name, digest, hashlib.sha256(claims_text.encode()).hexdigest(), body, tuple(evidence)
    )


def _render(
    concepts: tuple[_Concept, ...], routes: dict[str, str]
) -> tuple[_Document, ...] | Failure:
    request = _RenderRequest(tuple(_Document(item.path, item.body) for item in concepts), routes)
    node = shutil.which("node")
    if node is None:
        return Failure(Code.MARKDOWN, str(PARSER))
    try:
        result = subprocess.run(
            [node, str(PARSER)],
            input=json.dumps(asdict(request)),
            text=True,
            capture_output=True,
            timeout=30,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return Failure(Code.MARKDOWN, str(PARSER))
    raw = _json(result.stdout, str(PARSER))
    if result.returncode or not _record(raw) or raw.get("type") != "PROJECTED":
        return Failure(Code.MARKDOWN, str(PARSER))
    documents = raw.get("documents")
    if not _objects(documents) or len(documents) != len(concepts):
        return Failure(Code.MARKDOWN, str(PARSER))
    output: list[_Document] = []
    for expected, item in zip(concepts, documents, strict=True):
        if (
            not _record(item)
            or item.get("path") != expected.path
            or not isinstance(item.get("body"), str)
        ):
            return Failure(Code.MARKDOWN, expected.path)
        body = item["body"]
        if not isinstance(body, str):
            return Failure(Code.MARKDOWN, expected.path)
        output.append(_Document(expected.path, body))
    return tuple(output)


def _snippet(name: str) -> str:
    return OUTPUT + "/" + name.removeprefix("openwiki/").removesuffix(".md") + ".mdx"


def _walk_error(error: OSError) -> None:
    raise error


def _public_routes(root: Path) -> tuple[str, ...] | Failure:
    public = root / "docs/public"
    routes: list[str] = []
    try:
        for directory, folders, files in os.walk(public, onerror=_walk_error):
            folders[:] = [
                name
                for name in folders
                if not name.startswith(".") and name not in {"snippets", "node_modules", "build"}
            ]
            for name in files:
                if (
                    not name.startswith(".")
                    and name != "AGENTS.md"
                    and Path(name).suffix in {".md", ".mdx"}
                ):
                    routes.append(
                        (Path(directory) / name).relative_to(public).with_suffix("").as_posix()
                    )
    except OSError:
        return Failure(Code.IO, "docs/public")
    return tuple(routes)


def project(root: Path, manifest: Manifest, tracked: frozenset[str]) -> Projection | Failure:
    concepts: list[_Concept] = []
    routes: dict[str, str] = {}
    for view in manifest.views:
        for name in view.concepts:
            routes.setdefault(name, view.route)
    for name in sorted(routes):
        item = _concept(root, name, tracked)
        if isinstance(item, Failure):
            return item
        concepts.append(item)
    rendered = _render(tuple(concepts), routes)
    if isinstance(rendered, Failure):
        return rendered
    artifacts: list[Artifact] = []
    for concept, document in zip(concepts, rendered, strict=True):
        claims_path = (
            "openwiki/.claims/"
            + concept.path.removeprefix("openwiki/").removesuffix(".md")
            + ".json"
        )
        changed = sum(item.status is EvidenceStatus.CHANGED for item in concept.evidence)
        unassessed = sum(item.status is EvidenceStatus.NOT_ASSESSED for item in concept.evidence)
        qualification = (
            "Recorded evidence matches current file bytes. This comparison does not prove behavior."
        )
        if changed or unassessed:
            qualification = "Recorded evidence differs from current source or needs further assessment. This explanation does not prove current behavior."
        header = (
            "{/* Generated by docs/tooling/okf_public.py. Edit the canonical OKF through OpenWiki. */}\n\n"
            f"Shared [OKF source](https://github.com/amichne/kast/blob/main/{concept.path}) and "
            f"[recorded Claims](https://github.com/amichne/kast/blob/main/{claims_path}).\n\n"
            f"<Info>\n{qualification}\n</Info>\n\n"
        )
        artifacts.append(Artifact(_snippet(concept.path), header + document.body))
    for view in manifest.views:
        imports = list(view.imports)
        imports.extend(
            f'import OkfConcept{index} from "/{_snippet(name).removeprefix("docs/public/")}"'
            for index, name in enumerate(view.concepts)
        )
        body = [
            "{/* Generated by docs/tooling/okf_public.py. Edit docs/okf-public.json for presentation. */}",
            *imports,
        ]
        body.extend(f'<a id="{anchor}" />' for anchor in view.anchors)
        body.extend(view.diagrams)
        body.extend(f"<OkfConcept{index} />" for index in range(len(view.concepts)))
        artifacts.append(
            Artifact(
                f"docs/public/{view.route}.mdx",
                "---\n" + view.frontmatter + "\n---\n\n" + "\n\n".join(body) + "\n",
            )
        )
    report = Report(
        tuple(
            ConceptReport(item.path, item.sha256, item.claimsSha256, item.evidence)
            for item in concepts
        ),
        tuple(view.route for view in manifest.views),
        manifest.authored,
    )
    artifacts.append(
        Artifact(OUTPUT + "/provenance.json", json.dumps(asdict(report), indent=2) + "\n")
    )
    return Projection(tuple(artifacts), report)


def run(root: Path, write: bool) -> Report | Failure:
    text = _read(root, MANIFEST)
    if isinstance(text, Failure):
        return text
    manifest = parse_manifest(text)
    if isinstance(manifest, Failure):
        return manifest
    # This metadata inventory establishes tracking, without reading source content.
    git = shutil.which("git")
    if git is None:
        return Failure(Code.TRACKING, ".")
    try:
        result = subprocess.run(
            [git, "ls-files", "-z"], cwd=root, capture_output=True, timeout=30, check=False
        )
    except (OSError, subprocess.TimeoutExpired):
        return Failure(Code.TRACKING, ".")
    if result.returncode:
        return Failure(Code.TRACKING, ".")
    try:
        tracked = frozenset(result.stdout.decode("utf-8").rstrip("\0").split("\0"))
    except UnicodeError:
        return Failure(Code.TRACKING, ".")
    generated_routes = {view.route for view in manifest.views}
    authored_routes = {item.route for item in manifest.authored}
    routes = generated_routes | authored_routes
    actual = _public_routes(root)
    if isinstance(actual, Failure):
        return actual
    missing = routes - set(actual)
    unexpected = set(actual) - routes
    # Write mode can restore declared generated shells. Authored pages have no generator.
    invalid_missing = missing & authored_routes if write else missing
    if invalid_missing or unexpected or len(set(actual)) != len(actual):
        return Failure(
            Code.INPUT, "public route inventory: " + ", ".join(sorted(invalid_missing | unexpected))
        )
    projection = project(root, manifest, tracked)
    if isinstance(projection, Failure):
        return projection
    expected = {item.path for item in projection.artifacts if item.path.startswith(OUTPUT + "/")}
    existing = {
        path.relative_to(root).as_posix() for path in (root / OUTPUT).rglob("*") if path.is_file()
    }
    retired = sorted(existing - expected)
    for name in retired:
        content = _read(root, name)
        if not write or isinstance(content, Failure) or not content.startswith(GENERATED):
            return Failure(Code.DRIFT, name)
    for item in projection.artifacts:
        current = _read(root, item.path)
        if write:
            if isinstance(current, Failure) and current.code not in {Code.IO}:
                return current
            try:
                destination = root / item.path
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(item.text, encoding="utf-8")
            except OSError:
                return Failure(Code.IO, item.path)
        elif isinstance(current, Failure) or current != item.text:
            return Failure(Code.DRIFT, item.path)
    for name in retired:
        try:
            (root / name).unlink()
        except OSError:
            return Failure(Code.IO, name)
    return projection.report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--repo", type=Path, default=ROOT)
    args = parser.parse_args()
    result = run(args.repo.resolve(), args.write)
    print(json.dumps(asdict(result), indent=2))
    return 1 if isinstance(result, Failure) else 0


if __name__ == "__main__":
    raise SystemExit(main())
